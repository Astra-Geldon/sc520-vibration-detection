//=====================================================================
//  color_shading.v  ——  颜色阴影（color shading）校正
//
//  为什么需要它
//      对最新抓帧做 40x40 块统计后发现：画面偏色**不是全局的**，而是
//      「左侧偏品红 G-R ≈ -10、中央偏绿 G-R ≈ +21、右侧偏品红 G-R ≈ -5」
//      的水平渐变。跨 2 小时、不同 AWB 版本、不同 PLL 配置抓的 4 帧，
//      该分布相关系数 0.993~0.998、平均绝对差仅 0.4~1.3 -> 是镜头/传感器
//      的固定 pattern（微透镜斜入射效应），不是光源、也不是 AWB 算错。
//
//      全局 AWB 和 CCM 只能整体调增益，修不了这种**空间不均匀**的偏色。
//      正确做法是分区增益：把画面切成 10x6 块，每块查一组 R/B 增益。
//
//  原理
//      gain_r[块] = G_mean[块] / R_mean[块]
//      gain_b[块] = G_mean[块] / B_mean[块]
//      R' = R * gain_r,  B' = B * gain_b,  G 直通
//      -> 块内三通道相等，且**整体亮度不变**（G 不做任何改动）
//
//  网格为什么是 10x6
//      x[10:7] -> 0..9（1280/128 = 10 列），y[9:7] -> 0..5（720/128 ≈ 6 行）
//      块索引 = blk_y*10 + blk_x，用移位加法实现（*10 = *8 + *2），无除法。
//      实测：8x6 后逐像素 |G-R| 从 8.94 降到 3.96，已接近噪声底
//      （2.71 级噪声 x sqrt(2) = 3.83），再加密网格无意义。
//
//  资源
//      x/y 计数器 21 FF + LUT ROM 约 60x18 bit + 2 个 8x9 乘法（2 DSP）
//      纯组合像素路径，**零延迟**，与 img_proc / osd_overlay 的约定一致。
//=====================================================================
module color_shading (
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire        I_vs,        // 场同步：清行计数
    input  wire        I_de,        // 像素有效
    input  wire [23:0] I_data,      // 来自 awb_simple（RGB888）
    input  wire [ 1:0] I_k_sel,   // CSC 强度档 0:关 1:0.5 2:0.75 3:1.0
    output wire [23:0] O_data       // 送 img_proc
);

    //------------------------------------------------------------------
    //  x / y 计数（与 osd_overlay.v 同一套写法）
    //------------------------------------------------------------------
    reg [10:0] S_x;
    reg [ 9:0] S_y;
    reg        S_de_d;

    wire S_line_end = S_de_d & ~I_de;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            S_x    <= 11'd0;
            S_y    <= 10'd0;
            S_de_d <= 1'b0;
        end
        else begin
            S_de_d <= I_de;

            if (I_de)            S_x <= S_x + 1'b1;
            else                 S_x <= 11'd0;

            if (I_vs)            S_y <= 10'd0;
            else if (S_line_end) S_y <= S_y + 1'b1;
        end
    end

    //------------------------------------------------------------------
    //  块索引与块内位置
    //    blk_x = S_x[10:7] (0..9)    blk_y = S_y[9:7] (0..5)
    //    fx    = S_x[6:0]            fy    = S_y[6:0]      （块内偏移，0..127）
    //    *10 = *8 + *2，纯移位加法；无除法器
    //------------------------------------------------------------------
    wire [3:0] S_bx  = S_x[10:7];
    wire [6:0] S_fx  = S_x[6:0];

    // 右 / 下邻居，边界钳位到自身（最后一块不外插）
    // 右邻居，边界钳位到自身（最后一列不外插）
    wire [3:0] S_bx1 = (S_bx == 4'd9) ? 4'd9 : (S_bx + 1'b1);

    //------------------------------------------------------------------
    //  相邻两列的增益（1D表，各例化一次）
    //------------------------------------------------------------------
    wire [8:0] S_gr0, S_gr1, S_gb0, S_gb1;

    // 当前先回退到历史1D表：2段表在y=360处硬切换，会产生整条水平色带。
    // 垂直方向的细化等多场景标定完成后再做低阶平滑，不在像素路径中直接硬切。
    color_shading_lut u_lut0 (.I_blk(S_bx ), .O_gain_r(S_gr0), .O_gain_b(S_gb0));
    color_shading_lut u_lut1 (.I_blk(S_bx1), .O_gain_r(S_gr1), .O_gain_b(S_gb1));

    //------------------------------------------------------------------
    //  水平线性插值（加权平均，两通道共用权重）
    //    g = (g0*(128-fx) + g1*fx) >> 7
    //
    //  为什么用 1D 表 + 水平插值（而不是 10x6 + 双线性）
    //    实测（摄像头画面注入连续 shading，块边界 G-R 跳变）：
    //      10x6 硬跳变      -> 竖 14.11、横 10.69   （现状，有可见条带）
    //      10x6 双线性      -> 竖  0.48、横  0.48   （11 个乘法，SWNS -10.9ns 跑不动）
    //      10x1 + 水平插值  -> 竖  0.48、横  0.44   （2 个插值乘法，时序友好）
    //    把 6 行按列垂直平均成 1D 后，垂直方向不再分块 -> 横条自然消失；
    //    代价是垂直方向有 +-4% 的缓慢渐变误差（残差 1.87），肉眼不可见。
    //------------------------------------------------------------------
    // ★ 时优化：fx 只取高 5 位（块内 32 级插值，每级 4 像素）
    //   台阶幅度 = 相邻列增益差(33%)/32 = 1%，肉眼不可见。
    //   乘法位宽从 9x8 降到 9x6，加法从 18 位降到 16 位。
    wire [4:0]  S_fx5 = S_x[6:2];               // 0..31
    wire [5:0]  S_w0  = {1'b0, S_fx5};          // 0..31
    wire [5:0]  S_w1  = 6'd32 - {1'b0, S_fx5};  // 1..32

    // 9x6 + 9x6 <= 18880（15 位），权重和 = 32，所以 >>5
    wire [15:0] S_sum_r = S_gr0*S_w1 + S_gr1*S_w0;
    wire [15:0] S_sum_b = S_gb0*S_w1 + S_gb1*S_w0;

    // 插值是凸组合，结果 <= max(表值) = 295 < 512，所以取 9 位就够，无需钳位
    // （省掉比较+mux 一级逻辑，实测对时序有 0.5~1ns 帮助）
    //------------------------------------------------------------------
    //  ★ CSC 强度缩放（2026-10-24）
    //    当前交接表仍是单场景的绝对校正表；多场景候选表才是归一化空间形状。
    //    两种表不能混用。这里统一把表值偏离1.0的程度乘以系数k，供现场诊断：
    //      I_k_sel=0 -> k=0（CSC 关闭）  1 -> 0.5   2 -> 0.75   3 -> 1.0（默认）
    //    gain_eff = 256 + (gain_tab - 256) * k
    //------------------------------------------------------------------
    wire [2:0] S_K = (I_k_sel == 2'd0) ? 3'd0 :
                     (I_k_sel == 2'd1) ? 3'd2 :
                     (I_k_sel == 2'd2) ? 3'd3 : 3'd4;

    function [8:0] f_k_scale;
        input [8:0] g;
        input [2:0] K;
        reg   [8:0] d;
        // d 最大为255，K最大为4，乘积需要10位。
        // 安路TD对 d*K 的窄位宽表达式会截断高位；例如
        // 192*4=768 若先截成9位，得到的强度就不是1.0档。
        reg   [9:0] d_prod;
        begin
            d = (g >= 9'd256) ? (g - 9'd256) : (9'd256 - g);
            d_prod = d * K;
            d = d_prod >> 2;
            f_k_scale = (g >= 9'd256) ? (9'd256 + d) : (9'd256 - d);
        end
    endfunction

    wire [8:0] S_gain_r = f_k_scale(S_sum_r[13:5], S_K);

    //------------------------------------------------------------------
    //  增益寄存一拍（★ 只延迟增益，不延迟像素数据）
    //
    //  为什么这样做：插值逻辑 + 2 个应用乘法串在一条组合路径上，
    //  实测 SWNS -1.736ns，75 MHz 跑不动。中间打一拍把路径切成两段。
    //
    //  为什么不延迟数据：延迟数据会让画面右移 1 像素、破坏 hdmi_mixer 的
    //  window_active 对齐；只延迟增益则没有错位问题。
    //
    //  误差分析：增益在块内沿 x 变化约 33%/128像素 = 0.26%/像素，
    //  用"上一像素的增益"最多错 0.26% -> 约 0.7 个灰度级，肉眼不可见。
    //------------------------------------------------------------------
    reg [8:0] S_gain_r_r;
    reg [8:0] S_gain_b_r;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            S_gain_r_r <= 9'd256;
            S_gain_b_r <= 9'd256;
        end
        else begin
            S_gain_r_r <= S_gain_r;
            S_gain_b_r <= S_gain_b;
        end
    end
    wire [8:0] S_gain_b = f_k_scale(S_sum_b[13:5], S_K);

    //------------------------------------------------------------------
    //  像素路径：纯组合，零延迟。G 直通，只动 R / B。
    //------------------------------------------------------------------
    wire [16:0] S_r_mul = I_data[23:16] * S_gain_r_r;     // 8 x 9 = 17 位
    wire [16:0] S_b_mul = I_data[7:0]   * S_gain_b_r;

    wire [7:0] S_r_out = (S_r_mul[16:8] > 8'hFF) ? 8'hFF : S_r_mul[16:8];
    wire [7:0] S_b_out = (S_b_mul[16:8] > 8'hFF) ? 8'hFF : S_b_mul[16:8];

    assign O_data = {S_r_out, I_data[15:8], S_b_out};

endmodule
