module awb  #(   
    parameter IMG_HEIGHT = 1080,
    parameter IMG_WIDTH  = 1920
) 
(
    input                   I_clk  ,
    input                   I_rst_n,


    input                   I_tlast  ,
    input                   I_tuser  ,
    input [95:0]            I_tdata  ,
    input                   I_tvalid , 
    output                  I_tready ,

    output                  O_tlast  ,
    output                  O_tuser  ,
    output [95:0]           O_tdata  ,
    output                  O_tvalid ,
    input                   O_tready
);

/*****************************************************************
                          RGB565תRGB888                                        
*****************************************************************/

    // //RGB565??????888
    // wire [4:0]  rgb565_r   = I_st_data[11+:5];
    // wire [5:0]  rgb565_g   = I_st_data[5+:6];
    // wire [4:0]  rgb565_b   = I_st_data[0+:5];
    
    // wire [23:0] rgb888     = {{rgb565_r[4:0],rgb565_r[2:0]},{rgb565_g[5:0],rgb565_g[1:0]},{rgb565_b[4:0],rgb565_b[2:0]}};
    
    // wire [7:0]  rgb888_r   = rgb888[16+:8];
    // wire [7:0]  rgb888_g   = rgb888[8+:8] ;
    // wire [7:0]  rgb888_b   = rgb888[0+:8] ;
    
  /*****************************************************************
                          中间信号                                        
*****************************************************************/


  reg         I_tvalid_r0,I_tvalid_r1;
  reg  [95:0] I_tdata_d0,I_tdata_d1;


  //累加RGB通道的�??
  reg  [31:0]         sum_r[0:3];
  reg  [31:0]         sum_g[0:3];
  reg  [31:0]         sum_b[0:3];

  
  wire  [95:0]        data_d0 ;
  wire                valid_d0;
  wire                I_tuser_r0;    

  reg                 I_tuser_r1;

  reg   [95:0]        data_d1 ;
  reg                 valid_d1;
  reg   [9:0]         rgb_sum[0:3];//每个像素点RGB的和
  /*****************************************************************
                            平均值计�??                                      
*****************************************************************/

// 对输入数据和有效信号进行寄存，形成流水线
always @(posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n) begin
        I_tdata_d0  <= 0;
        I_tdata_d1  <= 0;
        {I_tvalid_r0,I_tvalid_r1} <= 0;
    end else begin
        I_tdata_d0  <= I_tdata   ;
        I_tdata_d1  <= I_tdata_d0;
        I_tvalid_r0 <= I_tvalid;
        I_tvalid_r1 <= I_tvalid_r0;
    end
end

// 将输入数据拆分为4个像素的RGB分量
wire [7:0] rgb888_r_d[0:3];
wire [7:0] rgb888_g_d[0:3];
wire [7:0] rgb888_b_d[0:3];

assign  rgb888_r_d[0] = I_tdata[16+:8];
assign  rgb888_g_d[0] = I_tdata[8+:8];
assign  rgb888_b_d[0] = I_tdata[0+:8];


// 将输入数据拆分为4个像素的RGB分量
wire [7:0] rgb888_r_d0[0:3];
wire [7:0] rgb888_g_d0[0:3];
wire [7:0] rgb888_b_d0[0:3];

assign  rgb888_r_d0[0] = I_tdata_d0[16+:8];
assign  rgb888_g_d0[0] = I_tdata_d0[8+:8];
assign  rgb888_b_d0[0] = I_tdata_d0[0+:8];


        ///削弱白色
        always @(posedge I_clk or negedge I_rst_n) begin
            if(!I_rst_n) begin
                rgb_sum[0] <= 0;
            end
            else if(I_tvalid)begin
                rgb_sum[0] <= rgb888_r_d[0] + rgb888_g_d[0] + rgb888_b_d[0];
            end
        end

        // 对每个通道的值进行累加，用于计算平均值
        always @(posedge I_clk or negedge I_rst_n) begin
            if (!I_rst_n || I_tuser) begin
                // 复位或行开始信号有效时，清零累加器
                sum_r[0] <= 1;
                sum_g[0] <= 1;
                sum_b[0] <= 1;
            end else if (I_tvalid_r0 && (rgb_sum[0] < 720)) begin
                // 当输入有效时，累加RGB分量的值
                sum_r[0] <= sum_r[0] + rgb888_r_d0[0];
                sum_g[0] <= sum_g[0] + rgb888_g_d0[0];
                sum_b[0] <= sum_b[0] + rgb888_b_d0[0];
            end
        end

  /*****************************************************************
        串行除法器（2026-10-24 替换原 2 个 50 级流式除法器）
  *****************************************************************/
  // 改造说明
  //   原设计：2 个 divider IP（PIPLE=50），start=I_tvalid_r1 每拍启动，
  //           配合 96bit x 50 拍的 signal_delay 做逐像素对齐。
  //           实测这两个除法器占 u_awb 的 90%：
  //             div_gen_G_R_r1  845 lut / 1,084 ripple / 2,803 seq
  //             divide_G_B_r1   785 lut / 1,084 ripple / 2,710 seq
  //           合计约 4,700 slice。
  //   新设计：行末（I_tlast）锁存累加和，串行算 R、B 两个增益（各 48 拍），
  //           整行使用同一增益。行消隐有 370 拍，96 拍足够算完。
  //           signal_delay(50 拍) 保持不动，所以下游时序完全不变。
  //
  //   !! 商必须用移位累积（{quo[46:0], bit}），不能用 quo[cnt]<=bit 这种
  //      变量索引赋值 —— 实测综合结果不对（详见 docs/worklog.md 2026-10-24）。
  //   !! 用 S_dquo_f 组合出最后一位，因为 cnt==0 那一拍的试减结果还没进寄存器。

  reg [19:0] in_r_r1;
  reg [19:0] in_b_r1;

  localparam [1:0] DIV_IDLE = 2'd0,
                   DIV_R    = 2'd1,
                   DIV_B    = 2'd2;

  reg [1:0]  S_dst;
  reg [5:0]  S_dcnt;
  reg [47:0] S_ddvd;
  reg [31:0] S_ddvs;
  reg [48:0] S_drem;
  reg [47:0] S_dquo;
  reg [31:0] S_sum_g_h;

  wire [48:0] S_drem_nx = {S_drem[47:0], S_ddvd[S_dcnt]};
  wire        S_dsub    = (S_drem_nx >= {17'd0, S_ddvs});
  wire [47:0] S_dquo_f  = {S_dquo[46:0], S_dsub};

  always @(posedge I_clk or negedge I_rst_n) begin
      if (!I_rst_n) begin
          S_dst     <= DIV_IDLE;
          S_dcnt    <= 6'd47;
          S_ddvd    <= 48'd0;
          S_ddvs    <= 32'd1;
          S_drem    <= 49'd0;
          S_dquo    <= 48'd0;
          S_sum_g_h <= 32'd1;
          in_r_r1   <= 20'h10000;
          in_b_r1   <= 20'h10000;
      end
      else begin
          case (S_dst)
              DIV_IDLE: begin
                  if (I_tlast && I_tvalid) begin
                      S_sum_g_h <= sum_g[0];
                      S_ddvd    <= {sum_g[0], 16'd0};
                      S_ddvs    <= sum_r[0];
                      S_drem    <= 49'd0;
                      S_dquo    <= 48'd0;
                      S_dcnt    <= 6'd47;
                      S_dst     <= DIV_R;
                  end
              end

              DIV_R: begin
                  if (S_dsub) begin
                      S_drem <= S_drem_nx - {17'd0, S_ddvs};
                      S_dquo <= {S_dquo[46:0], 1'b1};
                  end
                  else begin
                      S_drem <= S_drem_nx;
                      S_dquo <= {S_dquo[46:0], 1'b0};
                  end

                  if (S_dcnt == 6'd0) begin
                      in_r_r1 <= (|S_dquo_f[47:20]) ? 20'hfffff : S_dquo_f[19:0];
                      S_ddvd  <= {S_sum_g_h, 16'd0};
                      S_ddvs  <= sum_b[0];
                      S_drem  <= 49'd0;
                      S_dquo  <= 48'd0;
                      S_dcnt  <= 6'd47;
                      S_dst   <= DIV_B;
                  end
                  else begin
                      S_dcnt <= S_dcnt - 1'b1;
                  end
              end

              DIV_B: begin
                  if (S_dsub) begin
                      S_drem <= S_drem_nx - {17'd0, S_ddvs};
                      S_dquo <= {S_dquo[46:0], 1'b1};
                  end
                  else begin
                      S_drem <= S_drem_nx;
                      S_dquo <= {S_dquo[46:0], 1'b0};
                  end

                  if (S_dcnt == 6'd0) begin
                      in_b_r1 <= (|S_dquo_f[47:20]) ? 20'hfffff : S_dquo_f[19:0];
                      S_dst   <= DIV_IDLE;
                  end
                  else begin
                      S_dcnt <= S_dcnt - 1'b1;
                  end
              end

              default: S_dst <= DIV_IDLE;
          endcase
      end
  end


     
    signal_delay #(
        .IMG_HEIGHT   (IMG_HEIGHT),
        .IMG_WIDTH    (IMG_WIDTH ),
        .DATA_WIDTH   (96  ),
        .DELAY_CYCLE  (50)
    )signal_delay_d (
        /*input                       */ .I_clk  (I_clk  ),
        /*input                       */ .I_rst_n(I_rst_n),
        /*input                       */ .I_tuser(I_tuser),  //synthesis keep 
        /*input  wire                 */ .I_valid(I_tvalid_r1),  //synthesis keep 
        /*input  wire [DATA_WIDTH-1:0]*/ .I_data (I_tdata_d1 ),   //synthesis keep 
        /*output wire                 */ .O_valid(valid_d0   ),  //synthesis keep 
        /*output wire [DATA_WIDTH-1:0]*/ .O_data (data_d0    ),   //synthesis keep 
        /*output wire                 */ .O_tuser(I_tuser_r0 )
    );


    ////信号同步
    always @(posedge I_clk or negedge I_rst_n) begin
      if (!I_rst_n) begin
          valid_d1 <= 0;
          data_d1  <= 0;
          I_tuser_r1 <= 0;
      end else begin
          valid_d1 <= valid_d0;
          data_d1  <= data_d0 ;
          I_tuser_r1 <= I_tuser_r0;
      end
    end
/*****************************************************************
