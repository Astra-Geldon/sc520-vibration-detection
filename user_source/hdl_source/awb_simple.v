//=====================================================================
//  awb_simple.v  ——  白平衡 + 亮度补偿（替代厂商 AWB）
//
//  背景
//      厂商 `awb.v` 用了 1,919 lut / 6,098 seq / 10 ERAM / 8 DSP
//      （折算约 5,438 slice），贵在它做**同帧内延迟对齐**：
//      要把整帧像素延迟到统计完成再应用，所以要 10 块 ERAM + 6,098 个触发器。
//      为给振动算法腾资源，这里用**固定增益**替代它，成本约 100 LUT / 3 DSP。
//
//  增益是怎么标定的
//      抓一帧"关闭 AWB"的画面，算出三通道均值，反推需要多少增益才能让
//      三通道相等、且整体亮度达到目标值。具体步骤见 awb_simple.v 的参数注释，
//      以及 docs/优秀成功经验/白平衡标定方法.md。
//
//  限制（必须知道）
//      · 只对**标定时的光源**准确。换白炽灯/窗边自然光，颜色会偏。
//      · 传感器模拟增益变化后要重新标定（当前 AE 固定最大值，暂无影响）。
//
//  为什么没做自适应（踩过的坑，别再重复）
//      第一版用"上一帧统计 -> 除法 -> 平滑"，连踩两个坑：
//        1) 组合除法器（14 次迭代串起来）导致 HDMI_PIXEL_CLK 组
//           SWNS -6.295ns / STNS -85ns，14 个端点违例，75 MHz 跑不动；
//        2) 改成串行状态机后，用 `S_quo[S_bit] <= 1'b1` 这种**变量索引
//           非阻塞赋值**累积商，综合结果不对（Python 模型验证算法本身正确，
//           说明是 RTL 写法与综合器不匹配），实测增益恒偏小、画面暗一半且逐帧跳。
//      要做自适应，正确路线：串行状态机 + **移位累积**商
//      （`S_quo <= {S_quo[12:0], bit}`），且先在仿真里跑通再上板。
//=====================================================================
module awb_simple #(
    // 三个通道的 Q8 增益（256 = 1.0x）。改这里即可重新标定。
    // 2026-10-24 第二次标定（第一组系数是按厂商 AWB 反推的，换场景后偏青）：
    //   实测输入 RGB = (86.0, 97.2, 107.6)，B 偏强、R 偏弱 -> 画面偏青
    //   白平衡比例 = (1.130, 1.000, 0.903)，归一化系数 0.989（让平均增益≈1，避免过强放大）
    //   目标输出 mean=110 -> 增益如下，预期三通道都到 110，白点不偏
    parameter [8:0] GAIN_R = 9'd327,    // 1.277x
    parameter [8:0] GAIN_G = 9'd290,    // 1.133x
    parameter [8:0] GAIN_B = 9'd262     // 1.023x
)(
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire        I_vs,        // 固定增益版不用，保留端口兼容
    input  wire        I_de,
    input  wire [23:0] I_data,      // 来自 video_out（RGB888）
    output wire [23:0] O_data       // 送 img_proc
);

    //------------------------------------------------------------------
    //  像素路径：三个 8x9 乘法 + 饱和，纯组合、零延迟
    //------------------------------------------------------------------
    wire [16:0] S_r_mul = I_data[23:16] * GAIN_R;   // 8 x 9 = 17 位
    wire [16:0] S_g_mul = I_data[15:8]  * GAIN_G;
    wire [16:0] S_b_mul = I_data[7:0]   * GAIN_B;

    // 右移 8 位（Q8），超过 255 饱和
    wire [7:0] S_r_out = (S_r_mul[16:8] > 8'hFF) ? 8'hFF : S_r_mul[16:8];
    wire [7:0] S_g_out = (S_g_mul[16:8] > 8'hFF) ? 8'hFF : S_g_mul[16:8];
    wire [7:0] S_b_out = (S_b_mul[16:8] > 8'hFF) ? 8'hFF : S_b_mul[16:8];

    assign O_data = {S_r_out, S_g_out, S_b_out};

    // 固定增益版不用这些输入，显式引用来避免"未使用"告警
    wire unused_ok = I_clk & I_rst_n & I_vs & I_de;

endmodule
