"""Generate scene-independent RGB shoulder coefficients; no runtime division.

The wide pixel peak p uses a knee at 208 and spans 128/64/32:
    target = min(255, 208 + span*(p-208)/(span+p-208)).
RGB share round(target/p * 65536). Tables are analytical, not camera training.
"""
from fractions import Fraction
from pathlib import Path


def shoulder_gain(peak, span):
    if peak <= 208:
        return 65536
    distance = peak - 208
    target = min(Fraction(255), Fraction(208) + Fraction(span * distance, span + distance))
    gain = target * 65536 / peak
    return (gain.numerator * 2 + gain.denominator) // (gain.denominator * 2)


def generate():
    root = Path(__file__).resolve().parents[1]
    lines = [
        '// Generated by tools/gen_highlight_shoulder_lut.py; do not hand-edit.',
        '// Analytical shared-RGB Q16 gains for peak209..511, spans128/64/32.',
        '// No image-dependent calibration, pixel multiplication or division here.',
        'module highlight_shoulder_lut (',
        '    input wire [8:0] I_peak,',
        '    output reg [47:0] O_gains // {weak16, medium16, strong16}',
        ');',
        '    always @(*) begin',
        '        case (I_peak)',
    ]
    for peak in range(209, 512):
        gains = [shoulder_gain(peak, span) for span in (128, 64, 32)]
        assert all(0 < gain < 65536 for gain in gains)
        packed = (gains[0] << 32) | (gains[1] << 16) | gains[2]
        lines.append(f"            9'd{peak}: O_gains = 48'h{packed:012x};")
    lines += ["            default: O_gains = 48'd0; // bypassed for peak<=208", '        endcase', '    end', 'endmodule', '']
    path = root / 'user_source/hdl_source/highlight_shoulder_lut.v'
    path.write_text('\n'.join(lines), encoding='ascii', newline='\n')
    return path


if __name__ == '__main__':
    print(generate())
